// Projection: copies canonical markdown into docs/generated/ for the site build.
// Sources stay where they live (single source of truth); generated/ is gitignored.
import { mkdirSync, copyFileSync, readdirSync, existsSync, writeFileSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const out = join(root, 'docs/generated')
mkdirSync(out, { recursive: true })

const map = {
  'kernel/KERNEL.md': 'kernel.md',
  'kernel/SOURCES.md': 'sources.md',
  'contract/CONTRACT.md': 'contract.md',
}
for (const [src, dst] of Object.entries(map)) {
  if (!existsSync(join(root, src))) { console.error(`assemble: missing ${src}`); process.exit(1) }
  copyFileSync(join(root, src), join(out, dst))
}
// Capabilities are project skills of this repo: .claude/skills/<name>/SKILL.md
for (const cap of readdirSync(join(root, '.claude', 'skills'))) {
  const skill = join(root, '.claude', 'skills', cap, 'SKILL.md')
  if (existsSync(skill)) copyFileSync(skill, join(out, `capability-${cap}.md`))
}
// The base CLAUDE.md proposal: the installable file plus its rationale.
{
  const body = readFileSync(join(root, 'kernel/CLAUDE.md.proposed'), 'utf8').trim()
  const rationale = readFileSync(join(root, 'docs/.vitepress/claude-md-rationale.md'), 'utf8').trim()
  writeFileSync(join(out, 'claude-md.md'),
`# A base CLAUDE.md

A proposal for \`~/.claude/CLAUDE.md\` — the user-scope memory file that is
concatenated into every project, in every session.

## Why it is this short

${rationale}

## The file

\`\`\`markdown
${body}
\`\`\`

## Where it does *not* belong

Anything that must not fail: a hook exits 0 or 2; this file is advice.
`)
}

writeFileSync(join(out, '.gitkeep-note.md'), '<!-- generated by assemble.mjs; never edit -->\n')
console.log('assembled docs/generated/')
