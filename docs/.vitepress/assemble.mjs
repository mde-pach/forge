// Projection: copies canonical markdown into docs/generated/ for the site build.
// Sources stay where they live (single source of truth); generated/ is gitignored.
import { mkdirSync, copyFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const out = join(root, 'docs/generated')
mkdirSync(out, { recursive: true })

const map = {
  'kernel/KERNEL.md': 'kernel.md',
  'kernel/SOURCES.md': 'sources.md',
  'contract/CONTRACT.md': 'contract.md',
  'FRICTIONS.md': 'frictions.md',
}
for (const [src, dst] of Object.entries(map)) {
  if (!existsSync(join(root, src))) { console.error(`assemble: missing ${src}`); process.exit(1) }
  copyFileSync(join(root, src), join(out, dst))
}
for (const cap of readdirSync(join(root, 'capabilities'))) {
  const skill = join(root, 'capabilities', cap, 'SKILL.md')
  if (existsSync(skill)) copyFileSync(skill, join(out, `capability-${cap}.md`))
}
writeFileSync(join(out, '.gitkeep-note.md'), '<!-- generated by assemble.mjs; never edit -->\n')
console.log('assembled docs/generated/')
